/**
 * @fileoverview Lithos UI date picker type definitions and interfaces.
 * - Defines selection modes, variants, formatting options, and configuration props for DatePicker and its compound subcomponents.
 */
import type { ReactNode } from 'react'
import type { Placement, FloatingContext } from '@floating-ui/react'
import type { DateRange, CalendarProps } from '../calendar/calendar.types'
import type { LithosClass } from '../../../utils/cn'

/**
 * Selection mode behavior for the date picker component.
 */
export type DatePickerMode = 'single' | 'range' | 'multiple'

/**
 * Visual layout variant for the date picker.
 * - 'default': single calendar popover.
 * - 'dual': side-by-side two-month calendars with dedicated range inputs and action controls.
 */
export type DatePickerVariant = 'default' | 'dual'

/**
 * Formatting strategy used to render the selected date in the input field.
 * - 'numeric': strict DD/MM/YYYY formatting.
 * - 'natural': localized readable date formatting (e.g. 'Oct 25, 2026').
 */
export type DatePickerDateFormat = 'numeric' | 'natural'

/**
 * Value union representing the selected state across different date picker modes.
 */
export type DatePickerValue = Date | DateRange | Date[] | null

/**
 * Quick shortcut preset option configuration.
 */
export interface DatePickerPreset {
  /** Display label for the preset item. */
  label: string

  /** Date or date range value assigned when selecting this preset. */
  value: DatePickerValue
}

/**
 * Configuration options interface accepted by the `useDatePicker` headless hook.
 */
export interface UseDatePickerOptions {
  /**
   * Selection mode behavior.
   * @default 'single'
   */
  mode?: DatePickerMode | undefined

  /** Controlled selected date value. */
  value?: DatePickerValue | undefined

  /** Uncontrolled initial selected date value. */
  defaultValue?: DatePickerValue | undefined

  /** Callback fired when the selected date or range value changes. */
  onChange?: ((value: DatePickerValue) => void) | undefined

  /** Controlled popover visibility state. */
  open?: boolean | undefined

  /**
   * Uncontrolled initial popover visibility state.
   * @default false
   */
  defaultOpen?: boolean | undefined

  /** Callback fired when the popover visibility changes. */
  onOpenChange?: ((open: boolean) => void) | undefined

  /**
   * Floating UI placement alignment for the popover overlay relative to the trigger.
   * @default 'bottom-start'
   */
  placement?: Placement | undefined

  /**
   * Whether focus is trapped modally inside the calendar popover dialog while open.
   * @default false
   */
  modal?: boolean | undefined

  /**
   * Whether to automatically close the popover dialog upon completing a selection.
   * Defaults to true in single mode and false in range/multiple modes.
   */
  closeOnSelect?: boolean | undefined

  /** Locale identifier string used for internationalized date formatting and weekday names. */
  locale?: string | undefined

  /**
   * Date text formatting strategy displayed inside the trigger input.
   * @default 'numeric'
   */
  dateFormat?: DatePickerDateFormat | undefined
}

/**
 * Internal shared context state provided to DatePicker compound subcomponents.
 */
export interface DatePickerContextValue {
  /** Active selection mode behavior. */
  mode: DatePickerMode

  /** Currently selected date, range, or date array value. */
  value: DatePickerValue | undefined

  /** State updater to update the current selection value. */
  setValue: (value: DatePickerValue) => void

  /** Popover open state. */
  open: boolean

  /** State updater to toggle or set the popover open state. */
  setOpen: (open: boolean) => void

  /** Active locale identifier string. */
  locale?: string | undefined

  /** Active date formatting style. */
  dateFormat?: DatePickerDateFormat | undefined

  /** Whether the popover closes automatically on date selection. */
  closeOnSelect: boolean

  /** Ref callback assigned to the reference trigger DOM element. */
  triggerRef: (node: HTMLElement | null) => void

  /** Ref callback assigned to the floating popover content DOM element. */
  floatingRef: (node: HTMLElement | null) => void

  /** Computed inline positioning styles generated by Floating UI. */
  floatingStyles: React.CSSProperties

  /** Floating UI context instance governing interactions and focus management. */
  floatingContext: FloatingContext

  /** Floating UI prop getters for the trigger element. */
  getReferenceProps: (userProps?: Record<string, unknown>) => Record<string, unknown>

  /** Floating UI prop getters for the floating popover container. */
  getFloatingProps: (userProps?: Record<string, unknown>) => Record<string, unknown>

  /** Minimum selectable date threshold. */
  minDate?: Date | undefined

  /** Maximum selectable date threshold. */
  maxDate?: Date | undefined

  /** Whether the picker is disabled. */
  disabled?: boolean | undefined

  /** Whether the picker is marked invalid with error styling. */
  invalid?: boolean | undefined

  /** Whether the popover traps focus modally. */
  modal: boolean
}

/**
 * Props for the `DatePickerTrigger` compound subcomponent.
 */
export interface DatePickerTriggerProps {
  /** Trigger element child. */
  children: ReactNode

  /** Whether to clone the child element and merge trigger props onto it rather than rendering a wrapper. */
  asChild?: boolean | undefined

  /** Custom CSS classes applied to the trigger element. */
  className?: LithosClass | undefined
}

/**
 * Standard sizing scales supported by date picker input triggers.
 */
export type DatePickerInputSizes = 'default' | 'sm' | 'md' | 'lg'

/**
 * Props for the `DatePickerInput` text input trigger component.
 */
export interface DatePickerInputProps {
  /** Placeholder text displayed when no date is entered. Defaults to 'DD/MM/YYYY'. */
  placeholder?: string | undefined

  /** Whether the input is disabled. */
  disabled?: boolean | undefined

  /** Whether the input is in an invalid error state. */
  invalid?: boolean | undefined

  /**
   * Sizing scale variant governing height and padding.
   * @default 'default'
   */
  size?: DatePickerInputSizes | undefined

  /**
   * Whether to render an inline clear button when a date is selected.
   * @default false
   */
  clearable?: boolean | undefined

  /** Formatting style used for displaying the date in the input. */
  dateFormat?: DatePickerDateFormat | undefined

  /** Optional leading adornment element or icon. */
  startAdornment?: ReactNode | undefined

  /** Optional trailing adornment element or icon. */
  endAdornment?: ReactNode | undefined

  /** Custom CSS classes applied to the input container. */
  className?: LithosClass | undefined

  /** Accessible label description for the input field. */
  'aria-label'?: string | undefined
}

/**
 * Props for the floating popover container `DatePickerContent` component.
 */
export interface DatePickerContentProps {
  /** Popover dialog content elements. */
  children?: ReactNode | undefined

  /**
   * Whether to portal the popover to document.body to avoid stacking context clipping.
   * @default true
   */
  portaled?: boolean | undefined

  /** Animation transition duration in milliseconds. */
  transitionDuration?: number | undefined

  /** Custom CSS classes applied to the popover container. */
  className?: LithosClass | undefined

  /** Custom inline styles applied to the popover container. */
  style?: React.CSSProperties | undefined
}

/**
 * Props for the quick preset shortcuts sidebar `DatePickerPresets` component.
 */
export interface DatePickerPresetsProps {
  /** List of selectable preset shortcuts. Uses default presets if omitted. */
  presets?: DatePickerPreset[] | undefined

  /** Custom CSS classes applied to the presets container. */
  className?: LithosClass | undefined

  /** Callback invoked when a preset item is clicked. */
  onSelectPreset?: ((preset: DatePickerPreset) => void) | undefined
}

/**
 * Props for the dual month range input header `DatePickerRangeInputs` component.
 */
export interface DatePickerRangeInputsProps {
  /**
   * Label for the range start input field.
   * @default 'From'
   */
  fromLabel?: string | undefined

  /**
   * Label for the range end input field.
   * @default 'To'
   */
  toLabel?: string | undefined

  /**
   * Whether the input fields can be typed into directly.
   * @default true
   */
  editable?: boolean | undefined

  /** Custom CSS classes applied to the range inputs container. */
  className?: LithosClass | undefined
}

/**
 * Props for the range action confirmation footer `DatePickerActions` component.
 */
export interface DatePickerActionsProps {
  /** Callback triggered when the Apply button is clicked. */
  onApply?: (() => void) | undefined

  /** Callback triggered when the Cancel button is clicked. */
  onCancel?: (() => void) | undefined

  /** Custom CSS classes applied to the action footer container. */
  className?: LithosClass | undefined

  /**
   * Text label for the Apply button.
   * @default 'Apply'
   */
  applyLabel?: string | undefined

  /**
   * Text label for the Cancel button.
   * @default 'Cancel'
   */
  cancelLabel?: string | undefined
}

/**
 * Props for the side-by-side dual month calendar subcomponent `DatePickerDualCalendar`.
 */
export interface DatePickerDualCalendarProps {
  /**
   * Index of the first day of the week (0 for Sunday, 1 for Monday, etc.).
   * @default 0
   */
  firstDayOfWeek?: 0 | 1 | 2 | 3 | 4 | 5 | 6 | undefined

  /** Array of specific dates or day numbers that cannot be selected. */
  disabledDates?: (Date | number)[] | undefined

  /** Custom predicate function to dynamically disable specific calendar dates. */
  isDateDisabled?: ((date: Date) => boolean) | undefined

  /** Custom CSS classes applied to the dual calendar container. */
  className?: LithosClass | undefined
}

/**
 * Props for the root turnkey `DatePicker` component.
 */
export interface DatePickerProps
  extends
    UseDatePickerOptions,
    Omit<CalendarProps, 'value' | 'defaultValue' | 'onChange' | 'mode' | 'classes' | 'className' | 'locale'> {
  /** Custom children when using compound composition. If omitted, default input and popover are rendered. */
  children?: ReactNode | undefined

  /**
   * Visual layout variant.
   * @default 'default'
   */
  variant?: DatePickerVariant | undefined

  /** Input placeholder text. Defaults to 'DD/MM/YYYY' for single and 'DD/MM/YYYY - DD/MM/YYYY' for range. */
  placeholder?: string | undefined

  /** Whether the date picker input and trigger are disabled. */
  disabled?: boolean | undefined

  /** Whether the date picker is displayed in an invalid error state with alert styling. */
  invalid?: boolean | undefined

  /** Height and padding size scale variant for the input trigger. */
  size?: DatePickerInputSizes | undefined

  /** Whether to render an inline clear button inside the input trigger. */
  clearable?: boolean | undefined

  /** Whether to render the quick presets sidebar inside the popover dialog. */
  showPresets?: boolean | undefined

  /** Custom list of quick preset shortcuts. */
  presets?: DatePickerPreset[] | undefined

  /** Whether to show dedicated From and To editable input fields above the calendar in range mode. */
  showRangeInputs?: boolean | undefined

  /** Whether to show Apply and Cancel action buttons in range mode. */
  showActions?: boolean | undefined

  /**
   * Whether to portal the calendar popover dialog to document.body.
   * @default true
   */
  portaled?: boolean | undefined

  /** Custom CSS classes applied to the root container. */
  className?: LithosClass | undefined

  /** Callback invoked when the Apply action button is clicked. */
  onApply?: (() => void) | undefined

  /** Callback invoked when the Cancel action button is clicked. */
  onCancel?: (() => void) | undefined
}
